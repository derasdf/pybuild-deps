"""Tests for the uv-based dependency resolver."""

import subprocess
import sys
from pathlib import Path

import pytest

from pybuild_deps import compile_build_dependencies
from pybuild_deps.compile_build_dependencies import (
    ResolvedDependency,
    _parse_compiled_output,
    resolve_with_uv,
)
from pybuild_deps.exceptions import PyBuildDepsError, UnsolvableDependenciesError


def test_resolved_dependency_is_frozen():
    """ResolvedDependency is immutable."""
    dep = ResolvedDependency(name="foo", version="1.0")
    with pytest.raises(AttributeError):
        dep.name = "bar"


def test_parse_compiled_output_collects_every_hash():
    """All --hash lines for a pinned version are captured, other comments ignored."""
    text = (
        "# This file was autogenerated by uv\n"
        "#    uv pip compile ...\n"
        "cffi==1.15.1 \\\n"
        "    --hash=sha256:aaa \\\n"
        "    --hash=sha256:bbb \\\n"
        "    --hash=sha256:ccc\n"
        "    # via cryptography\n"
        "wheel==0.40.0 \\\n"
        "    --hash=sha256:ddd\n"
        "setuptools==69.0.0\n"
    )
    results = _parse_compiled_output(text, package="foo==1.0")
    assert results == [
        ResolvedDependency(
            name="cffi",
            version="1.15.1",
            hashes=("sha256:aaa", "sha256:bbb", "sha256:ccc"),
            via=frozenset({"cryptography"}),
        ),
        ResolvedDependency(name="wheel", version="0.40.0", hashes=("sha256:ddd",)),
        ResolvedDependency(name="setuptools", version="69.0.0"),
    ]


@pytest.mark.parametrize(
    ("package", "annotation", "expected"),
    [
        ("foo==1.0", "# via -r requirements.in", {"foo"}),
        ("Foo_Bar==1.0", "# via -r requirements.in", {"foo-bar"}),
        ("foo @ https://example.com/foo.tar.gz", "# via -r requirements.in", {"foo"}),
        ("foo==1.0", "# via -r requirements.in, packaging", {"foo", "packaging"}),
        ("foo==1.0", "# via hatchling, pluggy", {"hatchling", "pluggy"}),
        ("foo==1.0", "# via -c constraints.txt, packaging", {"packaging"}),
    ],
)
def test_parse_compiled_output_annotations(package, annotation, expected):
    """Inline and post-hash annotations map uv's input file to the package built."""
    outputs = [
        f"setuptools==69.0.0  {annotation}\n",
        f"setuptools==69.0.0 \\\n    --hash=sha256:aaa\n    {annotation}\n",
    ]
    results = [_parse_compiled_output(text, package)[0].via for text in outputs]
    assert results == [frozenset(expected)] * 2


class FakeUv:
    """Stand-in for subprocess.run that records what uv would see on each call."""

    def __init__(self):
        self.returncodes = [0]
        self.stderr = ""
        self.calls = []

    def __call__(self, cmd, cwd, **kwargs):
        """Snapshot the files given to uv and answer with a canned resolution."""
        files = {path.name: path.read_text() for path in Path(cwd).iterdir()}
        self.calls.append((cmd, files))
        Path(cwd, "requirements.txt").write_text("wheel==0.40.0\n")
        returncode = self.returncodes[len(self.calls) - 1]
        return subprocess.CompletedProcess(cmd, returncode, "", self.stderr)


@pytest.fixture
def fake_uv(monkeypatch):
    """Patch subprocess.run and the uv binary lookup."""
    fake = FakeUv()
    monkeypatch.setattr(subprocess, "run", fake)
    monkeypatch.setattr(compile_build_dependencies, "find_uv_bin", lambda: "/bin/uv")
    return fake


UV_COMMAND = [
    "/bin/uv",
    "pip",
    "compile",
    "--no-config",
    "--python",
    sys.executable,
    "--annotation-style",
    "line",
    "-o",
    "requirements.txt",
    "requirements.in",
]


@pytest.mark.parametrize(
    ("generate_hashes", "extra_args"), [(False, []), (True, ["--generate-hashes"])]
)
def test_resolve_command(fake_uv, generate_hashes, extra_args):
    """Run the bundled uv binary for this interpreter, ignoring uv config."""
    resolve_with_uv(["wheel"], package="foo==1.0", generate_hashes=generate_hashes)
    assert fake_uv.calls == [(UV_COMMAND + extra_args, {"requirements.in": "wheel\n"})]


def test_resolve_with_options_and_pins(fake_uv):
    """Options lead the input file; pins compatible with deps become constraints."""
    resolve_with_uv(
        ["setuptools>=42", "wheel"],
        package="foo==1.0",
        pins=["setuptools==40.0.0", "wheel==0.40.0", "packaging==24.0"],
        options=["--index-url https://example.com/simple"],
    )
    assert fake_uv.calls == [
        (
            [*UV_COMMAND, "-c", "constraints.txt"],
            {
                "requirements.in": (
                    "--index-url https://example.com/simple\nsetuptools>=42\nwheel\n"
                ),
                "constraints.txt": "wheel==0.40.0\npackaging==24.0\n",
            },
        )
    ]


def test_resolve_falls_back_to_preferences(fake_uv):
    """Without a solution under the pins, they are passed again as preferences."""
    fake_uv.returncodes = [1, 0]
    results = resolve_with_uv(["wheel"], package="foo==1.0", pins=["wheel==0.30.0"])
    assert fake_uv.calls[1] == (
        UV_COMMAND,
        {"requirements.in": "wheel\n", "requirements.txt": "wheel==0.30.0\n"},
    )
    assert results == [ResolvedDependency(name="wheel", version="0.40.0")]


def test_resolve_unsolvable(fake_uv):
    """Exit status 1 from uv means no solution: UnsolvableDependenciesError."""
    fake_uv.returncodes = [1]
    fake_uv.stderr = "  No solution found\n"
    with pytest.raises(UnsolvableDependenciesError) as exc_info:
        resolve_with_uv(["wheel"], package="foo==1.0")
    assert exc_info.value.package == "foo==1.0"
    assert exc_info.value.unsolvable_deps == "No solution found"


def test_resolve_error_is_not_retried(fake_uv):
    """Other uv failures, like a network error, are raised as they are."""
    fake_uv.returncodes = [2]
    with pytest.raises(PyBuildDepsError) as exc_info:
        resolve_with_uv(["wheel"], package="foo==1.0", pins=["wheel==0.40.0"])
    assert not isinstance(exc_info.value, UnsolvableDependenciesError)
    assert len(fake_uv.calls) == 1


@pytest.mark.parametrize(
    ("module", "attr"),
    [(compile_build_dependencies, "find_uv_bin"), (subprocess, "run")],
)
def test_resolve_raises_when_uv_missing(monkeypatch, module, attr):
    """A missing uv binary surfaces PyBuildDepsError, not a raw OSError."""

    def _missing(*args, **kwargs):
        raise FileNotFoundError

    monkeypatch.setattr(module, attr, _missing)
    with pytest.raises(PyBuildDepsError):
        resolve_with_uv(["wheel"], package="test")


def test_resolve_raises_on_timeout(monkeypatch):
    """A resolution timeout surfaces PyBuildDepsError."""

    def _timeout(*args, **kwargs):
        raise subprocess.TimeoutExpired(cmd="uv", timeout=300)

    monkeypatch.setattr(subprocess, "run", _timeout)
    with pytest.raises(PyBuildDepsError):
        resolve_with_uv(["wheel"], package="test")


def test_resolve_offline(local_index):
    """Real uv resolves from the options and annotates requirements."""
    results = resolve_with_uv(["backend"], package="foo==1.0", options=local_index)
    assert results == [
        ResolvedDependency(name="backend", version="1.0", via=frozenset({"foo"})),
        ResolvedDependency(name="helper", version="3.0", via=frozenset({"backend"})),
    ]


def test_resolve_offline_pins_hold(local_index):
    """Compatible pins hold, even if that means an older version elsewhere.

    uv would pick tool 2.0 on its own; with helper pinned to 2.0 it has to
    settle for tool 1.0, as pip-tools did.
    """
    results = resolve_with_uv(
        ["tool"], package="foo==1.0", pins=["helper==2.0"], options=local_index
    )
    assert {dep.name: dep.version for dep in results} == {
        "helper": "2.0",
        "tool": "1.0",
    }


def test_resolve_offline_pin_conflicting_with_deps(local_index, mocker):
    """A pin conflicting with a direct requirement is dropped up front."""
    run = mocker.spy(subprocess, "run")
    results = resolve_with_uv(
        ["helper>=3", "plugin"],
        package="foo==1.0",
        pins=["helper==1.0", "plugin==1.0"],
        options=local_index,
    )
    assert {dep.name: dep.version for dep in results} == {
        "helper": "3.0",
        "plugin": "1.0",
    }
    assert run.call_count == 1


def test_resolve_offline_pins_fall_back_to_preferences(local_index):
    """A pin conflicting further down only drops out; the others still hold."""
    results = resolve_with_uv(
        ["backend", "plugin"],
        package="foo==1.0",
        pins=["helper==1.0", "plugin==1.0"],
        options=local_index,
    )
    versions = {dep.name: dep.version for dep in results}
    assert versions == {"backend": "1.0", "helper": "3.0", "plugin": "1.0"}


def test_resolve_offline_hashes(local_index):
    """Hashes are generated for every resolved distribution."""
    results = resolve_with_uv(
        ["plugin"], package="foo==1.0", options=local_index, generate_hashes=True
    )
    assert [len(dep.hashes) for dep in results] == [1]
    assert results[0].hashes[0].startswith("sha256:")


def test_resolve_offline_unsolvable(local_index):
    """Conflicting requirements raise UnsolvableDependenciesError."""
    with pytest.raises(UnsolvableDependenciesError):
        resolve_with_uv(
            ["helper>=3", "helper<2"], package="foo==1.0", options=local_index
        )


@pytest.mark.e2e
def test_resolve_simple_deps():
    """Resolve a simple dependency list from PyPI with uv."""
    results = resolve_with_uv(["setuptools>=42", "wheel"], package="test")
    assert {"setuptools", "wheel"} <= {r.name for r in results}
    assert all(dep.version for dep in results)


@pytest.mark.e2e
def test_resolve_with_pins():
    """A compatible pin holds."""
    results = resolve_with_uv(
        ["setuptools>=42"], pins=["setuptools==75.8.2"], package="test"
    )
    assert {r.name: r.version for r in results}["setuptools"] == "75.8.2"
